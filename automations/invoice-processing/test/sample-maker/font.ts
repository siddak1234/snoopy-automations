/** The ink cells of `character`, as [column, row] pairs; a character the font lacks is a box. */
export function glyphCells(character: string): readonly (readonly [number, number])[] {
  const rows = (GLYPHS[character] ?? '#####|#...#|#...#|#...#|#...#|#...#|#####').split('|');
  const cells: [number, number][] = [];
  rows.forEach((row, y) => {
    for (let x = 0; x < GLYPH_WIDTH; x += 1) if (row[x] === '#') cells.push([x, y]);
  });
  return cells;
}
