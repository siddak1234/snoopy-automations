// autom8x-kit v1 — canonical: snoopy-backend/scripts/kit/map.mjs
// `npm run map` (STANDARD (c)): builds docs/MAP.md from the `map` and `rules`
// blocks of docs/docs-map.json and what git sees. Sorted, deterministic and
// LF-terminated, with no counts, dates or SHAs (they would change every PR), in
// eight sections: banner, read first, where to look by task, folders, package.json
// scripts, the kind lists, skills/agents/hooks, records by size. Fails when the
// result is over 300 lines. `--check` exits 1 when docs/MAP.md is stale;
// `--stdout` prints instead of writing. Kind lists (`as`): header-line, package,
// service, automation, expo-route, next-route, test-prefixes.
import { existsSync, readFileSync, realpathSync, statSync, writeFileSync } from 'node:fs';
import { posix } from 'node:path';
import { fileURLToPath } from 'node:url';
import { matches, visibleFiles } from './check-docs.mjs';

export const MAP_PATH = 'docs/MAP.md';
export const MAX_LINES = 300;
const KB = 1024;

const byText = (a, b) => (a < b ? -1 : a > b ? 1 : 0);
// Cut to n characters, never inside a code span.
function cut(text, n) {
  if (text.length <= n) return text;
  let s = text.slice(0, n - 1);
  if ((s.match(/`/gu) ?? []).length % 2) s = s.slice(0, s.lastIndexOf('`')).trimEnd();
  return `${s}…`;
}
const link = (path) => `[${path}](${posix.relative(posix.dirname(MAP_PATH), path)})`;
const code = (text) => `\`${String(text).replace(/`/gu, "'")}\``;
const clean = (text) => String(text ?? '').replace(/\s+/gu, ' ').replace(/[<>]/gu, '').trim();

function frontmatter(text) {
  const m = /^---\n([\s\S]*?)\n---/u.exec(text);
  const out = {};
  for (const line of (m?.[1] ?? '').split('\n')) {
    const kv = /^([A-Za-z-]+):\s*(.*)$/u.exec(line);
    if (kv) out[kv[1]] = kv[2].replace(/^["']|["']$/gu, '');
  }
  return out;
}

/** The first sentence of a README: its first paragraph line that is prose. */
function firstSentence(text) {
  const body = text.replace(/^---\n[\s\S]*?\n---\n/u, '').replace(/<!--[\s\S]*?-->/gu, '');
  const para = body.split(/\n\s*\n/u).map((p) => p.trim()).find((p) => p && !/^(?:#|!\[|\[!\[|<|```|\||>|-{3})/u.test(p));
  if (!para) return '';
  const flat = para.replace(/\s+/gu, ' ');
  return (/^.*?[.!?](?=\s|$)/u.exec(flat)?.[0] ?? flat).trim();
}

/** A source file's header: its first comment line; a JSON file's title or description. */
function headerLine(text, path = '') {
  if (path.endsWith('.json')) {
    try {
      const json = JSON.parse(text);
      return String(json.title ?? json.description ?? '');
    } catch {
      return '';
    }
  }
  for (const raw of text.split('\n').slice(0, 30)) {
    const line = raw.trim();
    // Past a shebang, blank lines, imports and the kit's own marker line.
    if (/^(?:#!|\/\*\*?$|import\b)/u.test(line) || line === '' || line.includes('autom8x-kit v1 —')) continue;
    const m = /^(?:\/\/+|\/\*+|\*|#)\s?(.*?)(?:\s*\*\/)?$/u.exec(line);
    return m ? m[1].trim() : '';
  }
  return '';
}

export function buildMap(root, files = visibleFiles(root)) {
  const has = new Set(files);
  const read = (p) => readFileSync(posix.join(root, p), 'utf8');
  const docsMap = JSON.parse(read('docs/docs-map.json'));
  const m = docsMap.map ?? {};
  const out = [];
  const section = (title, items) => out.push('', `## ${title}`, '', ...(items.length ? items : ['- none']));
  const ref = (p) => (has.has(p) ? link(p) : code(p));
  const pkg = (dir) => (has.has(`${dir}/package.json`) ? JSON.parse(read(`${dir}/package.json`)) : {});
  const dirs = [...new Set(files.flatMap((f) => f.split('/').slice(0, -1).map((_, i, a) => a.slice(0, i + 1).join('/'))))];
  const matched = (glob) => [...new Set([...files, ...dirs])].filter((p) => matches(glob, p)).sort(byText);
  const unitDirs = (glob) => [...new Set(matched(glob).map((p) => (p.endsWith('/package.json') ? posix.dirname(p) : p)).filter((p) => dirs.includes(p)))].sort(byText);
  const describe = (dir) => {
    if (has.has(`${dir}/CLAUDE.md`)) return clean(/^#\s+(.*)$/mu.exec(read(`${dir}/CLAUDE.md`))?.[1]);
    if (has.has(`${dir}/README.md`)) return clean(firstSentence(read(`${dir}/README.md`)));
    return clean(pkg(dir).description);
  };

  out.push(`<!-- Generated by scripts/kit/map.mjs from docs/docs-map.json and the git tree. Do not edit: run npm run map. -->`, '', `# ${docsMap.repo ?? posix.basename(root)}: map`);
  section('Read first', (m.readFirst ?? []).map((p) => `- ${ref(p)}`));
  section('Where to look by task', (docsMap.rules ?? []).map((r) => `- **${r.id}**: ${(r.code ?? []).map(code).join(', ')} → ${(r.docs ?? []).map(ref).join(', ')}`));
  const folders = (m.folders ?? []).length ? m.folders : [...new Set(files.filter((f) => f.includes('/')).map((f) => f.split('/')[0]))].sort(byText);
  section('Folders', folders.map((d) => `- ${code(`${d}/`)}: ${cut(describe(d), 160) || 'no description'}`));
  const scripts = Object.entries(pkg('.').scripts ?? (has.has('package.json') ? JSON.parse(read('package.json')).scripts : {}) ?? {});
  section('package.json scripts', scripts.sort(([a], [b]) => byText(a, b)).map(([k, v]) => `- ${code(`npm run ${k}`)}: ${code(cut(v, 80))}`));

  out.push('', '## Kind lists');
  for (const list of m.lists ?? []) {
    const items = [];
    if (list.as === 'header-line') {
      for (const f of matched(list.glob).filter((p) => has.has(p))) items.push(`- ${link(f)}: ${cut(clean(headerLine(read(f), f)), 140) || 'no header'}`);
    } else if (['package', 'service', 'automation'].includes(list.as)) {
      for (const d of unitDirs(list.glob)) {
        const p = pkg(d);
        let line = `- ${code(`${d}/`)}${p.name ? ` (${code(p.name)})` : ''}: ${cut(clean(p.description) || describe(d), 140) || 'no description'}`;
        if (list.as === 'automation') {
          const name = posix.basename(d);
          const versions = files.map((f) => new RegExp(`^manifests/${name}\\.v(\\d+)\\.json$`, 'u').exec(f)?.[1]).filter(Boolean).map(Number).sort((a, b) => a - b);
          line += versions.length ? ` · manifests ${versions.map((v) => `v${v}`).join(', ')}` : '';
        }
        items.push(line);
      }
    } else if (list.as === 'expo-route' || list.as === 'next-route') {
      for (const f of matched(list.glob).filter((p) => has.has(p))) {
        const base = posix.basename(f).replace(/\.[^.]+$/u, '');
        if (list.as === 'expo-route' && (base.startsWith('_') || base.startsWith('+'))) continue;
        if (list.as === 'next-route' && !['page', 'route'].includes(base)) continue;
        const segs = f.split('/').slice(1, -1).filter((s) => !/^\(.*\)$/u.test(s));
        if (list.as === 'expo-route' && base !== 'index') segs.push(base);
        items.push(`- ${code(`${list.as === 'next-route' && base === 'route' ? 'API ' : ''}/${segs.join('/')}`)}: ${link(f)}`);
      }
    } else if (list.as === 'test-prefixes') {
      const groups = new Map();
      for (const f of matched(list.glob).filter((p) => has.has(p))) {
        const prefix = posix.basename(f).split(/[.-]/u)[0];
        groups.set(posix.dirname(f), new Set([...(groups.get(posix.dirname(f)) ?? []), prefix]));
      }
      for (const [d, set] of [...groups].sort(([a], [b]) => byText(a, b))) items.push(`- ${code(`${d}/`)}: ${[...set].sort(byText).join(', ')}`);
    } else items.push(`- unknown list kind ${code(list.as)}`);
    out.push('', `### ${list.title}`, '', ...(items.length ? items : ['- none']));
  }

  const kit = [];
  for (const f of files.filter((p) => /^\.claude\/skills\/[^/]+\/SKILL\.md$/u.test(p)).sort(byText)) {
    const fm = frontmatter(read(f));
    kit.push(`- skill ${code(fm.name ?? posix.basename(posix.dirname(f)))}: ${cut(clean(fm.description), 160)} (${link(f)})`);
  }
  for (const f of files.filter((p) => /^\.claude\/agents\/[^/]+\.md$/u.test(p)).sort(byText)) {
    const fm = frontmatter(read(f));
    kit.push(`- agent ${code(fm.name ?? posix.basename(f, '.md'))}: ${cut(clean(fm.description), 160)} (${link(f)})`);
  }
  if (has.has('.claude/settings.json')) {
    const hooks = JSON.parse(read('.claude/settings.json')).hooks ?? {};
    for (const event of Object.keys(hooks).sort(byText)) {
      for (const group of hooks[event] ?? []) {
        for (const h of group.hooks ?? []) {
          const file = /\.claude\/hooks\/([\w./-]+)/u.exec(h.command ?? '')?.[1] ?? cut(clean(h.command), 60);
          kit.push(`- hook ${code(event)}${group.matcher ? ` (${code(group.matcher)})` : ''}: ${code(file)}`);
        }
      }
    }
  }
  section('Skills, agents and hooks', kit);

  const kind = (p) => ((docsMap.records?.archive ?? []).includes(p) ? 'archive' : (docsMap.records?.current ?? []).includes(p) ? 'current' : 'doc');
  const recordPaths = [...new Set([...(docsMap.records?.current ?? []), ...(docsMap.records?.archive ?? []), ...(m.readFirst ?? []), ...(docsMap.rules ?? []).flatMap((r) => r.docs ?? [])])].filter((p) => has.has(p) && existsSync(posix.join(root, p))).sort(byText);
  const buckets = [['Under 100 KB', 0, 100 * KB], ['100 KB to 1 MB', 100 * KB, 1024 * KB], ['Over 1 MB: grep only', 1024 * KB, Infinity]];
  out.push('', '## Records by size');
  for (const [title, lo, hi] of buckets) {
    const items = recordPaths.filter((p) => {
      const size = statSync(posix.join(root, p)).size;
      return size >= lo && size < hi;
    });
    out.push('', `### ${title}`, '', ...(items.length ? items.map((p) => `- ${link(p)} (${kind(p)})`) : ['- none']));
  }
  return `${out.join('\n')}\n`;
}

export function run(argv, root) {
  const text = buildMap(root);
  const count = text.split('\n').length - 1;
  if (count > MAX_LINES) return { code: 1, message: `map: ${MAP_PATH} would be ${count} lines, over ${MAX_LINES} — narrow the lists in docs/docs-map.json` };
  if (argv.includes('--stdout')) return { code: 0, stdout: text };
  const path = posix.join(root, MAP_PATH);
  if (argv.includes('--check')) {
    const current = existsSync(path) ? readFileSync(path, 'utf8') : '';
    return current === text ? { code: 0, message: `map: ${MAP_PATH} is current` } : { code: 1, message: `map: ${MAP_PATH} is stale — run npm run map and commit it` };
  }
  writeFileSync(path, text);
  return { code: 0, message: `map: wrote ${MAP_PATH}` };
}

const isMain = () => { try { return realpathSync(process.argv[1] ?? '') === fileURLToPath(import.meta.url); } catch { return false; } };
if (isMain()) {
  let result;
  try {
    const { spawnSync } = await import('node:child_process');
    const top = spawnSync('git', ['rev-parse', '--show-toplevel'], { encoding: 'utf8' });
    result = run(process.argv.slice(2), top.status === 0 ? top.stdout.trim() : process.cwd());
  } catch (error) {
    result = { code: 1, message: `map: ${error.message}` };
  }
  if (result.stdout !== undefined) process.stdout.write(result.stdout);
  if (result.message) (result.code ? console.error : console.log)(result.message);
  process.exitCode = result.code;
}
